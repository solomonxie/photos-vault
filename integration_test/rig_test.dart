import 'package:http/http.dart' as http;
import 'package:integration_test/integration_test.dart';
import 'package:photo_manager/photo_manager.dart';

void main() {
  IntegrationTestWidgetsFlutterBinding.ensureInitialized();

  testWidgets('rig: fake S3 over https and the Photos library', (t) async {
    final put = await http.put(Uri.https('localhost:9443', '/rig-bucket'));
    expect(put.statusCode, 200);
    final perm = await PhotoManager.requestPermissionExtend();
    expect(perm.isAuth, isTrue, reason: '$perm');
    final saved = await PhotoManager.editor.saveImage(
      Uint8List.fromList(_tinyPng),
      filename: 'rig.png',
    );
    expect(await AssetEntity.fromId(saved.id), isNotNull);
  });
}

